package dev.foabic.neoforge;

import dev.foabic.api.Foabic;
import dev.foabic.loader.resource.GeneratedResourcePack;
import net.minecraft.network.chat.Component;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackSelectionConfig;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.PathPackResources;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackCompatibility;
import net.minecraft.server.packs.repository.PackSource;
import net.minecraft.world.flag.FeatureFlags;
import net.neoforged.fml.loading.FMLEnvironment;
import net.neoforged.neoforge.event.AddPackFindersEvent;

import java.nio.file.Path;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

/**
 * Registers Foabic's generated assets as a fixed, always-on NeoForge resource
 * pack. It uses the public {@link AddPackFindersEvent} repository-source API
 * and a directory {@link PathPackResources}; no Mixin is involved.
 */
final class NeoForgeGeneratedResources {

    private static final System.Logger LOG = System.getLogger("Foabic/neoforge/resources");

    private NeoForgeGeneratedResources() {
    }

    static void onAddPackFinders(AddPackFindersEvent event) {
        if (!FMLEnvironment.getDist().isClient()) return;
        if (event.getPackType() != PackType.CLIENT_RESOURCES) return;

        Path root = Foabic.gameDirectory()
                .resolve(".foabic")
                .resolve(GeneratedResourcePack.DIRECTORY)
                .toAbsolutePath()
                .normalize();
        if (!GeneratedResourcePack.hasAssets(root)) {
            LOG.log(System.Logger.Level.DEBUG, "no generated Foabic assets to register");
            return;
        }

        PackLocationInfo location = new PackLocationInfo(
                "foabic_generated",
                Component.literal("Foabic generated block assets"),
                PackSource.BUILT_IN,
                Optional.empty());
        Pack.Metadata metadata = new Pack.Metadata(
                Component.literal("Models and textures generated by Foabic"),
                PackCompatibility.COMPATIBLE,
                FeatureFlags.DEFAULT_FLAGS,
                List.of());
        Pack.ResourcesSupplier supplier = new Pack.ResourcesSupplier() {
            @Override
            public net.minecraft.server.packs.PackMetadataResources openMetadata(PackLocationInfo info) {
                return new PathPackResources(info, root);
            }

            @Override
            public Stream<net.minecraft.server.packs.PackResources> openResources(
                    PackLocationInfo info, Pack.Metadata packMetadata) {
                return Stream.of(new PathPackResources(info, root));
            }
        };
        Pack pack = new Pack(location, supplier, metadata,
                new PackSelectionConfig(true, Pack.Position.TOP, true));
        event.addRepositorySource(consumer -> consumer.accept(pack));
        LOG.log(System.Logger.Level.INFO,
                "FOABIC_RESOURCE_PACK platform=neoforge id={0} root={1}", pack.getId(), root);
    }
}
